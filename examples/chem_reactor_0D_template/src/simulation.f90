!> chem_reactor_0D: adiabatic homogeneous 0D reactor (constant volume or constant pressure) with ignition delay time.
!> State y = [Y_1..Y_nS, T], integrated with CVODE (BDF, dense Newton). Source terms: fcmech_get_ydot (module fcmech,
!> generated by tools/scripts/chemistry/yaml2nga_lib_cf.py: detailed/skeletal YAML, or ARCANE QSS with --custom-f90).
!>
!> Standalone program: uses NGA2's libraries (precision, param, messager, parallel) and CVODE, not NGA2's core/main.f90.
!>
!> IDT (same definition as a Cantera reactor sweep, see 'python idt.py check'):
!>   on every CVODE step i: dT/dt_i = (T_i - T_i-1)/(t_i - t_i-1) at tm_step = (t_i + t_i-1)/2;
!>   IDT = tm_step of the largest dT/dt_i with tm_step >= 'IDT min time' and T_i > T0 + 'IDT min rise',
!>   searched until the first step with T > T0 + 'IDT window' (400 K). No such step before 'Max time' -> no ignition.
!> End of the run ('End mode'):
!>   flamemaster (default) : FlameMaster T0DIsoChor rule after ignition -- t > 3 IDT and > 3 consecutive steps with
!>                           |dT|/T < 1e-3 and |dT/dt| < 8229 K/s (end state within ~0.3 K of equilibrium)
!>   fixed                 : t_end = max(4 IDT, 0.5 s)
!>   maxtime               : integrate to 'Max time'
!> Outputs: 'Result file' (IDT, end state, CPU; key value lines) and optional trajectory 'Output file'
!> (FlameMaster-style buffer of 'Number of outputs' rows: time, Y_1..Y_nS (X with 'Output mole fractions : .true.'), T, P, rho).
!> Naming: hr_ib_ = isobaric (constant P), hr_ic_ = isochoric (constant V).

!> Data shared with the CVODE right-hand sides (C binding cannot pass extra arguments)
module hr_cvode_data
   use precision, only: WP
   real(WP), save :: hr_ib_P = 0.0_WP     !< pressure of the isobaric reactor (Pa)
   real(WP), save :: hr_ic_rho = 0.0_WP   !< density of the isochoric reactor (kg/m^3)
   real(WP), parameter :: Y_floor = 1.0e-50_WP, Y_floor_OUT = 1.0e-20_WP
end module hr_cvode_data

!> CVODE right-hand sides: adiabatic, ideal gas, NASA7 thermo from fcmech
module hr_rhs_mod
   use precision, only: WP
   use fcmech
   use hr_cvode_data
   use fsundials_core_mod
   use fnvector_serial_mod
   use, intrinsic :: ISO_C_BINDING
   implicit none
contains

   !> Isobaric: dT/dt = -sum(h_i/W_i dY_i/dt)/cp
   integer(c_int) function hr_ib_rhs(t, sunvec_y, sunvec_f, user_data) result(ierr) bind(C, name='hr_ib_rhs')
      real(c_double), value :: t
      type(N_Vector)        :: sunvec_y, sunvec_f
      type(c_ptr), value    :: user_data
      real(c_double), pointer :: yval(:), fval(:)
      real(WP), dimension(nS) :: h, cp, ydot
      real(WP) :: Tk, Cp_mix
      ierr = 0_c_int
      yval => FN_VGetArrayPointer(sunvec_y)
      fval => FN_VGetArrayPointer(sunvec_f)
      Tk = max(real(yval(nS+1), WP), 1.0_WP)
      call fcmech_get_thermodata(h, cp, Tk)
      Cp_mix = sum(real(yval(1:nS), WP)*cp/W_sp)
      call fcmech_get_ydot(hr_ib_P, Tk, real(yval(1:nS), WP), ydot)
      fval(1:nS) = real(ydot, c_double)
      fval(nS+1) = real(-sum(h*ydot/W_sp)/Cp_mix, c_double)
   end function hr_ib_rhs

   !> Isochoric: P = rho R T/W_mix, dT/dt = -sum((h_i - R T)/W_i dY_i/dt)/cv
   integer(c_int) function hr_ic_rhs(t, sunvec_y, sunvec_f, user_data) result(ierr) bind(C, name='hr_ic_rhs')
      real(c_double), value :: t
      type(N_Vector)        :: sunvec_y, sunvec_f
      type(c_ptr), value    :: user_data
      real(c_double), pointer :: yval(:), fval(:)
      real(WP), dimension(nS) :: h, cp, ydot
      real(WP) :: Tk, W_mix, Cv_mix, Ploc
      ierr = 0_c_int
      yval => FN_VGetArrayPointer(sunvec_y)
      fval => FN_VGetArrayPointer(sunvec_f)
      Tk = max(real(yval(nS+1), WP), 1.0_WP)
      W_mix = 1.0_WP/sum(real(yval(1:nS), WP)/W_sp)
      call fcmech_get_thermodata(h, cp, Tk)
      Cv_mix = sum(real(yval(1:nS), WP)*cp/W_sp) - Rcst/W_mix
      Ploc = hr_ic_rho*Rcst*Tk/W_mix
      call fcmech_get_ydot(Ploc, Tk, real(yval(1:nS), WP), ydot)
      fval(1:nS) = real(ydot, c_double)
      fval(nS+1) = real(-sum((h - Rcst*Tk)*ydot/W_sp)/Cv_mix, c_double)
   end function hr_ic_rhs
end module hr_rhs_mod


program chem_reactor_0D
   use precision, only: WP
   use string, only: str_medium, str_long
   use param, only: param_init, param_final, param_read, param_exists, param_getsize
   use parallel, only: parallel_init, parallel_final, amRoot
   use messager, only: messager_init, messager_final, die
   use fcmech
   use hr_cvode_data
   use hr_rhs_mod
   use fcvode_mod
   use fnvector_serial_mod
   use fsunmatrix_dense_mod
   use fsunlinsol_dense_mod
   use fsundials_core_mod
   use, intrinsic :: ISO_C_BINDING
   implicit none

   integer, parameter :: nT = nS + 1
   ! FlameMaster T0DIsoChor end-of-run thresholds
   real(WP), parameter :: fm_rel_T_plateau = 1.0e-3_WP, fm_dTdt_plateau_max = 8229.0_WP, fm_t_after_ign_mult = 3.0_WP
   integer, parameter :: fm_nothing_happens_exit = 3

   ! Inputs
   real(WP) :: T0, P0, time_end, idt_min_time, idt_min_rise, idt_window, rtol, atol
   character(len=str_medium) :: reactor_str, end_mode, output_file, result_file
   integer :: reactor_type                       ! 1 = isobar, 2 = isochor
   logical :: write_traj, traj_X
   ! State
   real(WP), dimension(nS) :: Y, X, h, cp
   real(WP) :: T, P, rho, W_mix, time, Tp, tp_
   ! IDT
   logical :: window_closed
   real(WP) :: idt, dTdt, dTdt_max, tm_step, t_stop
   ! FlameMaster end rule
   integer :: nothing_happens
   logical :: leave
   ! Trajectory buffer (FlameMaster SaveSolution/Reduce)
   integer :: Noutputs, act_length, delta_step_save
   real(WP), allocatable :: time_hist(:), T_hist(:), Y_hist(:,:)
   ! CVODE
   type(C_PTR) :: cvode_mem, sunctx
   type(N_Vector), pointer :: yvec
   type(SUNMatrix), pointer :: sunmat_A
   type(SUNLinearSolver), pointer :: sunlinsol_LS
   real(C_DOUBLE), dimension(nT), target :: ydata
   real(C_DOUBLE) :: tret(1)
   integer(C_INT) :: ierr
   integer(C_LONG) :: flag
   integer(C_LONG), target :: nst(1)
   integer :: i, iu, status_code
   real(WP) :: cpu0, cpu1
   character(len=str_medium), dimension(nS) :: species_names

   call parallel_init
   call messager_init
   call param_init
   call fcmech_get_speciesnames(species_names)

   ! ---------------------------------------------------------------- inputs
   call read_composition(Y)
   call param_read('Temperature', T0)
   call param_read('Pressure', P0)
   call param_read('Reactor', reactor_str, default='isochor')
   reactor_str = lower(reactor_str)
   select case (trim(reactor_str))
   case ('isochor', 'cv', 'constant volume')
      reactor_type = 2
   case ('isobar', 'cp', 'constant pressure')
      reactor_type = 1
   case default
      call die('[chem_reactor_0D] Reactor must be isochor (cv) or isobar (cp)')
   end select
   call param_read('Max time', time_end, default=1.0e4_WP)
   call param_read('IDT min time', idt_min_time, default=1.0e-6_WP)
   call param_read('IDT min rise', idt_min_rise, default=55.0_WP)
   call param_read('IDT window', idt_window, default=400.0_WP)
   call param_read('End mode', end_mode, default='flamemaster')
   end_mode = lower(end_mode)
   if (all(trim(end_mode) .ne. [character(len=11) :: 'flamemaster', 'fixed', 'maxtime'])) &
      call die('[chem_reactor_0D] End mode must be flamemaster, fixed or maxtime')
   call param_read('CVODE rtol', rtol, default=1.0e-10_WP)
   call param_read('CVODE atol', atol, default=1.0e-20_WP)
   call param_read('Result file', result_file, default='idt.res')
   write_traj = param_exists('Output file')
   if (write_traj) then
      call param_read('Output file', output_file)
      call param_read('Number of outputs', Noutputs, default=1000)
      call param_read('Output mole fractions', traj_X, default=.false.)
      if (Noutputs .lt. 2) call die('[chem_reactor_0D] Number of outputs must be >= 2')
      allocate(time_hist(Noutputs), T_hist(Noutputs), Y_hist(nS, Noutputs))
   end if

   ! ---------------------------------------------------------------- initial state
   Y = merge(0.0_WP, Y, Y .lt. Y_floor)
   Y = Y/sum(Y)
   T = T0; P = P0
   W_mix = 1.0_WP/sum(Y/W_sp)
   if (reactor_type .eq. 1) then
      hr_ib_P = P0
   else
      hr_ic_rho = P0*W_mix/(Rcst*T0)
   end if
   ydata(1:nS) = real(Y, C_DOUBLE)
   ydata(nT) = real(T0, C_DOUBLE)

   ! ---------------------------------------------------------------- CVODE
   ierr = FSUNContext_Create(SUN_COMM_NULL, sunctx)
   yvec => FN_VMake_Serial(int(nT, c_int64_t), ydata, sunctx)
   cvode_mem = FCVodeCreate(CV_BDF, sunctx)
   if (reactor_type .eq. 1) then
      ierr = FCVodeInit(cvode_mem, c_funloc(hr_ib_rhs), 0.0_C_DOUBLE, yvec)
   else
      ierr = FCVodeInit(cvode_mem, c_funloc(hr_ic_rhs), 0.0_C_DOUBLE, yvec)
   end if
   if (ierr .ne. CV_SUCCESS) call die('[chem_reactor_0D] FCVodeInit failed')
   ierr = FCVodeSStolerances(cvode_mem, real(rtol, C_DOUBLE), real(atol, C_DOUBLE))
   if (ierr .ne. CV_SUCCESS) call die('[chem_reactor_0D] FCVodeSStolerances failed')
   sunmat_A => FSUNDenseMatrix(int(nT, c_int64_t), int(nT, c_int64_t), sunctx)
   sunlinsol_LS => FSUNLinSol_Dense(yvec, sunmat_A, sunctx)
   ierr = FCVodeSetLinearSolver(cvode_mem, sunlinsol_LS, sunmat_A)
   if (ierr .ne. CV_SUCCESS) call die('[chem_reactor_0D] FCVodeSetLinearSolver failed')
   ierr = FCVodeSetMaxNumSteps(cvode_mem, 1000000_C_LONG)
   if (ierr .ne. CV_SUCCESS) call die('[chem_reactor_0D] FCVodeSetMaxNumSteps failed')
   t_stop = time_end
   ierr = FCVodeSetStopTime(cvode_mem, real(t_stop, C_DOUBLE))
   if (ierr .ne. CV_SUCCESS) call die('[chem_reactor_0D] FCVodeSetStopTime failed')

   ! ---------------------------------------------------------------- integration
   act_length = 0; delta_step_save = 1
   if (write_traj) call save_row(0.0_WP, Y, T, 0, .true.)
   window_closed = .false.; idt = -1.0_WP; dTdt_max = -huge(1.0_WP)
   nothing_happens = 0; status_code = 0
   time = 0.0_WP; Tp = T0; tp_ = 0.0_WP
   call cpu_time(cpu0)
   do
      flag = FCVode(cvode_mem, real(time_end, C_DOUBLE), yvec, tret(1), CV_ONE_STEP)
      if (flag .lt. 0) then
         status_code = int(flag)
         if (amRoot) write(*,'(a,i0)') '[chem_reactor_0D] CVODE failed with flag ', flag
         exit
      end if
      time = real(tret(1), WP)
      Y = real(ydata(1:nS), WP)
      T = real(ydata(nT), WP)
      ierr = FCVodeGetNumSteps(cvode_mem, nst)

      ! IDT: peak dT/dt between consecutive steps, until T first exceeds T0 + window
      if (.not. window_closed .and. time .gt. tp_) then
         dTdt = (T - Tp)/(time - tp_)
         tm_step = 0.5_WP*(time + tp_)
         if (tm_step .ge. idt_min_time .and. T .gt. T0 + idt_min_rise .and. dTdt .gt. dTdt_max) then
            dTdt_max = dTdt
            idt = tm_step
         end if
         if (T .gt. T0 + idt_window) then
            window_closed = .true.
            if (amRoot) write(*,'(a,es16.8,a)') '[chem_reactor_0D] IDT = ', idt, ' s'
            if (trim(end_mode) .eq. 'fixed') then
               t_stop = min(time_end, max(4.0_WP*idt, 0.5_WP, time))
               ierr = FCVodeSetStopTime(cvode_mem, real(t_stop, C_DOUBLE))
            end if
         end if
      end if

      ! FlameMaster plateau counter on consecutive steps
      if (time .gt. tp_) then
         if (abs((T - Tp)/T) .lt. fm_rel_T_plateau .and. abs((T - Tp)/(time - tp_)) .lt. fm_dTdt_plateau_max) then
            nothing_happens = nothing_happens + 1
         else
            nothing_happens = 0
         end if
      end if
      Tp = T; tp_ = time

      leave = time .ge. t_stop .or. int(flag) .eq. CV_TSTOP_RETURN
      if (trim(end_mode) .eq. 'flamemaster' .and. window_closed) then
         if (nothing_happens .gt. fm_nothing_happens_exit .and. time .gt. fm_t_after_ign_mult*idt) leave = .true.
      end if
      if (write_traj) then
         if (act_length .eq. Noutputs) call reduce_rows
         call save_row(time, Y, T, int(nst(1)), leave)
      end if
      if (leave) exit
   end do
   call cpu_time(cpu1)

   ! ---------------------------------------------------------------- results
   W_mix = 1.0_WP/sum(Y/W_sp)
   if (reactor_type .eq. 1) then
      P = hr_ib_P
   else
      P = hr_ic_rho*Rcst*T/W_mix
   end if
   rho = P*W_mix/(Rcst*T)
   X = Y/W_sp*W_mix
   if (amRoot) then
      open(newunit=iu, file=trim(result_file), status='replace', action='write')
      write(iu,'(a,1x,i0)') 'status', status_code
      write(iu,'(a,1x,a)') 'reactor', trim(merge('isobar ', 'isochor', reactor_type .eq. 1))
      write(iu,'(a,1x,i0)') 'ignited', merge(1, 0, window_closed)
      write(iu,'(a,1x,es25.16e3)') 'idt_s', idt
      write(iu,'(a,1x,es25.16e3)') 'dTdt_max', dTdt_max
      write(iu,'(a,1x,es25.16e3)') 'T0', T0
      write(iu,'(a,1x,es25.16e3)') 'P0', P0
      write(iu,'(a,1x,es25.16e3)') 't_end', time
      write(iu,'(a,1x,es25.16e3)') 'T_end', T
      write(iu,'(a,1x,es25.16e3)') 'P_end', P
      write(iu,'(a,1x,es25.16e3)') 'rho_end', rho
      write(iu,'(a,1x,es25.16e3)') 'cpu_s', real(cpu1 - cpu0, WP)
      write(iu,'(a,1x,i0)') 'nsteps', int(nst(1))
      do i = 1, nS
         write(iu,'(a,1x,es25.16e3)') 'X_'//trim(species_names(i)), X(i)
      end do
      close(iu)
      write(*,'(a,es14.6,a,f10.3,a)') '[chem_reactor_0D] end: t = ', time, ' s, T = ', T, ' K'
   end if
   if (write_traj .and. amRoot) call write_rows

   call FCVodeFree(cvode_mem)
   ierr = FSUNLinSolFree(sunlinsol_LS)
   call FSUNMatDestroy(sunmat_A)
   call FN_VDestroy(yvec)
   ierr = FSUNContext_Free(sunctx)
   call param_final
   call messager_final
   call parallel_final

contains

   !> Initial composition. Either 'Initial X <species>' / 'Initial Y <species>' lines, or
   !> 'Fuel : A B ..' + 'Fuel mole fractions : xA xB ..' + 'Oxidizer : O2 N2' + 'Oxidizer mole fractions : 1 3.76'
   !> + 'Equivalence ratio : phi'. phi as Cantera set_equivalence_ratio: fuel/oxidizer mole ratio =
   !> phi*(-o_ox)/o_fuel with o = sum_k x_k (n_C + n_S + n_H/4 - n_O/2) per mole of stream.
   subroutine read_composition(Yout)
      real(WP), dimension(nS), intent(out) :: Yout
      real(WP), dimension(nS) :: Xin, xf, xo
      real(WP) :: phi, o_f, o_o
      integer :: k
      logical :: anyX, anyY
      Xin = 0.0_WP; anyX = .false.; anyY = .false.
      if (param_exists('Equivalence ratio')) then
         call param_read('Equivalence ratio', phi)
         if (.not. param_exists('Fuel')) call die('[chem_reactor_0D] Equivalence ratio needs Fuel : <species ...>')
         call read_stream('Fuel', 'Fuel mole fractions', '', xf)
         call read_stream('Oxidizer', 'Oxidizer mole fractions', 'O2 N2', xo)
         o_f = o2_need(xf); o_o = o2_need(xo)
         if (o_f .le. 0.0_WP .or. o_o .ge. 0.0_WP) call die('[chem_reactor_0D] fuel/oxidizer cannot define phi')
         Xin = phi*(-o_o)*xf + o_f*xo
      else
         do k = 1, nS
            if (param_exists('Initial X '//trim(species_names(k)))) then
               call param_read('Initial X '//trim(species_names(k)), Xin(k)); anyX = .true.
            end if
            if (param_exists('Initial Y '//trim(species_names(k)))) then
               call param_read('Initial Y '//trim(species_names(k)), Xin(k)); anyY = .true.
            end if
         end do
         if (anyX .and. anyY) call die('[chem_reactor_0D] use either Initial X or Initial Y lines, not both')
         if (sum(Xin) .le. 0.0_WP) call die('[chem_reactor_0D] no initial composition given')
         if (anyY) then
            Yout = Xin/sum(Xin); return
         end if
      end if
      Xin = Xin/sum(Xin)
      Yout = Xin*W_sp/sum(Xin*W_sp)
   end subroutine read_composition

   !> Stream composition (normalized mole fractions) from 'tag : A B ..' and 'tagx : xA xB ..'
   subroutine read_stream(tag, tagx, def_names, x)
      character(len=*), intent(in) :: tag, tagx, def_names
      real(WP), dimension(nS), intent(out) :: x
      character(len=str_medium), dimension(nS) :: names
      character(len=str_long) :: line
      real(WP), allocatable :: v(:)
      integer :: j, n, p, q
      logical :: last
      call param_read(tag, line, default=def_names)
      n = 0; p = 0
      do j = 1, len_trim(line)                                 ! split on blanks (NGA2 param turns commas into blanks)
         if (line(j:j) .eq. ' ') cycle
         if (p .eq. 0) p = j
         last = j .eq. len_trim(line)
         if (.not. last) last = line(j+1:j+1) .eq. ' '
         if (last) then
            n = n + 1
            if (n .gt. nS) call die('[chem_reactor_0D] too many species in '//trim(tag))
            names(n) = line(p:j); p = 0
         end if
      end do
      allocate(v(n))
      if (param_exists(tagx)) then
         if (param_getsize(tagx) .ne. n) call die('[chem_reactor_0D] '//trim(tagx)//': one value per species')
         call param_read(tagx, v)
      else if (n .eq. 1) then
         v = 1.0_WP
      else if (trim(tag) .eq. 'Oxidizer' .and. n .eq. 2 .and. trim(names(1)) .eq. 'O2' .and. trim(names(2)) .eq. 'N2') then
         v = [1.0_WP, 3.76_WP]                                 ! default oxidizer: air, O2:N2 = 1:3.76
      else
         call die('[chem_reactor_0D] missing '//trim(tagx))
      end if
      x = 0.0_WP
      do j = 1, n
         q = species_index(names(j))
         if (q .le. 0) call die('[chem_reactor_0D] species not in mechanism: '//trim(names(j)))
         x(q) = x(q) + v(j)
      end do
      x = x/sum(x)
   end subroutine read_stream

   !> O2 needed for complete oxidation minus O2 contained, per mole of stream (Cantera convention)
   real(WP) function o2_need(x)
      real(WP), dimension(nS), intent(in) :: x
      character(len=2), dimension(nA) :: anames
      integer, dimension(nA,nS) :: comp
      integer :: a
      real(WP) :: w
      call fcmech_get_atomnames(anames)
      call fcmech_get_composition(comp)
      o2_need = 0.0_WP
      do a = 1, nA
         select case (trim(anames(a)))
         case ('C', 'S'); w = 1.0_WP
         case ('H'); w = 0.25_WP
         case ('O'); w = -0.5_WP
         case default; w = 0.0_WP
         end select
         o2_need = o2_need + w*sum(x*real(comp(a,:), WP))
      end do
   end function o2_need

   integer function species_index(name)
      character(len=*), intent(in) :: name
      integer :: k
      species_index = -1
      do k = 1, nS
         if (trim(species_names(k)) .eq. trim(adjustl(name))) species_index = k
      end do
   end function species_index

   function lower(s) result(r)
      character(len=*), intent(in) :: s
      character(len=len(s)) :: r
      integer :: k
      r = adjustl(s)
      do k = 1, len_trim(r)
         if (r(k:k) .ge. 'A' .and. r(k:k) .le. 'Z') r(k:k) = achar(iachar(r(k:k)) + 32)
      end do
   end function lower

   !> FlameMaster SaveSolution: keep every delta_step_save-th step (always the first and the last)
   subroutine save_row(time_k, Y_k, temp_k, n_step, force)
      real(WP), intent(in) :: time_k, temp_k
      real(WP), dimension(nS), intent(in) :: Y_k
      integer, intent(in) :: n_step
      logical, intent(in) :: force
      if (.not. (force .or. mod(n_step, delta_step_save) .eq. 0)) return
      act_length = act_length + 1
      time_hist(act_length) = time_k; T_hist(act_length) = temp_k; Y_hist(:, act_length) = Y_k
   end subroutine save_row

   !> FlameMaster Reduce: keep rows 1,3,5,... and double the stride
   subroutine reduce_rows
      integer :: k, m
      m = (act_length + 1)/2
      do k = 1, m
         time_hist(k) = time_hist(2*k-1); T_hist(k) = T_hist(2*k-1); Y_hist(:, k) = Y_hist(:, 2*k-1)
      end do
      act_length = m
      delta_step_save = 2*delta_step_save
   end subroutine reduce_rows

   subroutine write_rows
      integer :: k, j, u
      real(WP) :: Wm, Pk, rk, v
      open(newunit=u, file=trim(output_file), status='replace', action='write')
      write(u,'(a18)', advance='no') 'time'
      do j = 1, nS
         write(u,'(1x,a18)', advance='no') trim(species_names(j))//merge('-X', '-Y', traj_X)
      end do
      write(u,'(3(1x,a18))') 'T', 'P', 'rho'
      do k = 1, act_length
         Wm = 1.0_WP/sum(Y_hist(:, k)/W_sp)
         if (reactor_type .eq. 1) then
            Pk = hr_ib_P; rk = Pk*Wm/(Rcst*T_hist(k))
         else
            rk = hr_ic_rho; Pk = rk*Rcst*T_hist(k)/Wm
         end if
         write(u,'(es18.10)', advance='no') time_hist(k)
         do j = 1, nS
            v = Y_hist(j, k); if (traj_X) v = v/W_sp(j)*Wm
            write(u,'(1x,es18.10e3)', advance='no') merge(0.0_WP, v, abs(v) .lt. Y_floor_OUT)
         end do
         write(u,'(3(1x,es18.10))') T_hist(k), Pk, rk
      end do
      close(u)
   end subroutine write_rows

